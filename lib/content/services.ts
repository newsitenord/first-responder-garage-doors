export const SERVICE_BY_SLUG = new Map(SERVICES.map((s) => [s.slug, s]));

export function serviceTokens(city: string, county: string, st: string) {
  return {
    city,
    countyLabel: county ? `${county} County` : "your county",
    ST: st,
  };
}

export function fill(text: string, city: string, county: string, st: string): string {
  return text
    .replaceAll("{city}", city)
    .replaceAll("{countyLabel}", county ? `${county} County` : "your county")
    .replaceAll("{county}", county)
    .replaceAll("{ST}", st)
    .replaceAll("{City}", city);
}
